#!/usr/bin/env python3
"""Build the world page from the original atlas's shared DOM and assets."""

import argparse
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "world" / "index.html"


def shell(source):
    layout = source.split('<body>', 1)[1].split('    </footer>', 1)[0] + '    </footer>\n  </div>'
    # China's relief is georeferenced to East Asia. Keep the shared SVG layer
    # hooks and supply global land and water through the world adapter.
    layout = re.sub(r'<script>.*?</script>', '', layout, flags=re.S)
    layout = re.sub(r' data-href(?:-mobile)?="[^"]+"', '', layout)
    layout = '\n'.join(line.rstrip() for line in layout.split('\n'))
    layout = layout.replace('href="world/" aria-label="世界历史 / World history">世界历史',
                            'id="switch-china" href="./" aria-label="中国历史 / China history">中国历史')
    layout = layout.replace('id="txt-subtitle">中国历史地图 · 战国 → 今', 'id="txt-subtitle">世界历史地图')
    layout = layout.replace('aria-label="中国历史地图"', 'aria-label="世界历史地图"')
    layout = layout.replace('aria-valuemin="-403" aria-valuemax="2026" aria-valuenow="-403"',
                            'aria-valuemin="-3400" aria-valuemax="2024" aria-valuenow="1500"')

    shared = []
    # Loading mixins first lets the shared controller install them at once.
    # atlas_api would otherwise schedule a boot before the world data arrives.
    for path in ('lore_core', 'atlas_trace', 'atlas_search', 'atlas_api', 'app'):
        match = re.search(rf'<script\b[^>]*\bsrc="js/{path}\.js[^"\n]*"[^>]*></script>', source)
        if not match:
            raise ValueError(f"Missing shared script js/{path}.js")
        shared.append(f'  {match.group()}')
    stylesheet = re.search(r'<link\b[^>]*\bhref="css/style\.css[^"\n]*"[^>]*>', source)
    if not stylesheet:
        raise ValueError('Missing shared atlas stylesheet')

    assets = '\n'.join(shared)
    return f'''<!doctype html>
<!-- Generated by scripts/build_world_shell.py from the upstream atlas layout. -->
<html lang="zh-CN" class="world-atlas">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <base href="../">
  <title>世界历史地图 · 江山时序</title>
  <meta name="description" content="江山时序的世界历史地图，包含历代疆域与可追溯的世界历史大事。">
  <link rel="icon" type="image/svg+xml" href="assets/favicon.svg">
  {stylesheet.group()}
  <link rel="stylesheet" href="world/world.css">
</head>
<body>{layout}
  <p id="world-load-status" role="status">正在加载世界历史地图…</p>
{assets}
  <script>window.removeEventListener('DOMContentLoaded', window.HistoricalAtlasController._bootOnce);</script>
  <script type="module" src="world/world.js"></script>
</body>
</html>
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify that the saved layout is current')
    args = parser.parse_args()
    rendered = shell((ROOT / 'index.html').read_text(encoding='utf-8'))
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != rendered:
            parser.exit(1, 'Run python scripts/build_world_shell.py to sync the atlas layout.\n')
    else:
        OUTPUT.write_text(rendered, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
